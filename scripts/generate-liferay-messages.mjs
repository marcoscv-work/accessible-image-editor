/**
 * Writes the host-side messages dictionary for a Liferay portal module:
 * one literal `Liferay.Language.get('key')` call per editor key. The
 * calls must be literals, because the portal's language filter
 * substitutes them statically and a dynamic lookup would never be
 * replaced. Keys that already exist in the portal's global
 * Language.properties translate for free in every bundled locale; the
 * rest must be added there through the buildLang workflow.
 *
 * Usage: node scripts/generate-liferay-messages.mjs > liferayMessages.ts
 */

import {readFile} from 'node:fs/promises';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const source = await readFile(
	join(dirname(fileURLToPath(import.meta.url)), '../src/i18n/en.ts'),
	'utf8'
);

const keys = [...source.matchAll(/^\t'?([a-z0-9][a-z0-9:-]*)'?:/gm)]
	.map(([, key]) => key)
	.sort();

const lines = keys.map(
	(key) => `\t'${key}': Liferay.Language.get('${key}'),`
);

process.stdout.write(
	`import {EditorMessages} from 'accessible-image-editor';

/**
 * Generated by generate-liferay-messages.mjs. Regenerate after any
 * change to the editor's message catalogue.
 */
export const editorMessages: EditorMessages = {
${lines.join('\n')}
};
`
);
